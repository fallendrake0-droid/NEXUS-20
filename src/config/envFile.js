'use strict';

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { isPrivateLanIp } = require('./loadConfig');

/**
 * Zero-dependency `.env` reader, writer, and local Wi-Fi LAN IP detector.
 * Keeps secrets restricted to `0600` POSIX permissions (`SECURITY_PLAN.md`).
 */
function parseDotEnv(content) {
  const out = {};
  if (typeof content !== 'string' || !content) return out;

  const lines = content.split(/\r?\n/);
  for (const rawLine of lines) {
    const trimmed = rawLine.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const withoutExport = trimmed.startsWith('export ') ? trimmed.slice(7).trim() : trimmed;
    const eqIdx = withoutExport.indexOf('=');
    if (eqIdx <= 0) continue;

    const key = withoutExport.slice(0, eqIdx).trim();
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(key)) continue;

    let val = withoutExport.slice(eqIdx + 1).trim();
    if (
      (val.startsWith('"') && val.endsWith('"') && val.length >= 2) ||
      (val.startsWith("'") && val.endsWith("'") && val.length >= 2)
    ) {
      val = val.slice(1, -1);
    } else {
      const hashIdx = val.indexOf(' #');
      if (hashIdx !== -1) {
        val = val.slice(0, hashIdx).trim();
      }
    }
    out[key] = val;
  }
  return out;
}

function loadDotEnvFile(filePath) {
  if (!filePath || !fs.existsSync(filePath)) return { exists: false, values: {} };
  try {
    const raw = fs.readFileSync(filePath, 'utf8');
    return { exists: true, values: parseDotEnv(raw) };
  } catch {
    return { exists: false, values: {} };
  }
}

function formatEnvValue(val) {
  const str = val === undefined || val === null ? '' : String(val);
  if (/[\s#"']/.test(str)) {
    return `"${str.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
  }
  return str;
}

function serializeDotEnv(values = {}) {
  const lines = [
    '# NEXUS-20 Interactive Configuration (.env)',
    '# Generated by `node index.js setup` — edit anytime with `npm run setup` or `npm start`.',
    '# Permissions: 0600 (gitignored — never commit secrets).',
    ''
  ];

  for (const [key, val] of Object.entries(values)) {
    if (val === undefined || val === null || val === '') continue;
    lines.push(`${key}=${formatEnvValue(val)}`);
  }
  lines.push('');
  return lines.join('\n');
}

function writeDotEnvFile(filePath, values = {}) {
  const resolved = path.resolve(filePath);
  fs.mkdirSync(path.dirname(resolved), { recursive: true, mode: 0o700 });
  const body = serializeDotEnv(values);
  fs.writeFileSync(resolved, body, { encoding: 'utf8', mode: 0o600 });
  try {
    fs.chmodSync(resolved, 0o600);
  } catch {
    // Best-effort chmod on non-POSIX platforms
  }
  return resolved;
}

/**
 * Auto-detect the device's active private Wi-Fi / LAN IPv4 address (e.g. `192.168.1.168`).
 */
function detectLocalLanIp(fallback = '127.0.0.1') {
  try {
    const nets = os.networkInterfaces();
    const candidates = [];
    for (const ifaceList of Object.values(nets || {})) {
      for (const addr of ifaceList || []) {
        if (!addr || addr.internal) continue;
        const family = typeof addr.family === 'string' ? addr.family : `IPv${addr.family}`;
        if (family !== 'IPv4') continue;
        if (isPrivateLanIp(addr.address)) {
          candidates.push(addr.address);
        }
      }
    }
    // Prefer 192.168.x.x home Wi-Fi addresses first if multiple private interfaces exist
    const homeWifi = candidates.find((ip) => ip.startsWith('192.168.'));
    return homeWifi || candidates[0] || fallback;
  } catch {
    return fallback;
  }
}

module.exports = {
  parseDotEnv,
  loadDotEnvFile,
  serializeDotEnv,
  writeDotEnvFile,
  detectLocalLanIp
};
